#!/usr/bin/env python3
"""Write a mainnet load-test config: picks entry gateways of the live Nym network from the nym-api.

  pick_gateways.py --out CONFIG.toml --output-dir RUN_DIR [--gateways 2] [--clients 10] [--seed 1]
                   [--duration 240] [--drain 60] [--min-performance 0.95]

Only entry gateways (current rewarded set) with a client websocket port and performance at or above
the threshold are eligible; among them the choice is seeded, so a run is reproducible. The clients
use the SDK defaults for mixing and cover traffic (the live network's settings), random pairing, and
the same message load as the localnet experiments (6 messages/min of 50 KB per client).
"""
import argparse, json, random, urllib.request

NYM_API = 'https://validator.nymtech.net/api/v1/unstable/nym-nodes/skimmed'


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--out', required=True); ap.add_argument('--output-dir', required=True)
    ap.add_argument('--gateways', type=int, default=2); ap.add_argument('--clients', type=int, default=10)
    ap.add_argument('--seed', type=int, default=1); ap.add_argument('--duration', type=int, default=240)
    ap.add_argument('--min-performance', type=float, default=0.95)
    ap.add_argument('--session', choices=['connection', 'message'], default='connection',
                    help='path-selection session scope: per connection, or per message (a new session for every file)')
    ap.add_argument('--drain', type=int, default=60, help='max wait for files still in flight after the sending window, s')
    ap.add_argument('--strategy', default='baseline', help='path-selection strategy of the (single) group, e.g. khf:1,2, kw:2, alpha:0.5')
    ap.add_argument('--groups', default='', help='heterogeneous profiles: "name:count:mix_ms:send_ms:loop_ms:msgs_per_min:msg_bytes;..." '
                    '(empty field = client default); counts must add up to --clients')
    a = ap.parse_args()
    data = json.load(urllib.request.urlopen(NYM_API, timeout=60))['nodes']['data']
    eligible = sorted((n for n in data if n.get('role') == 'EntryGateway' and n.get('entry')
                       and n['entry'].get('ws_port') and float(n.get('performance', 0)) >= a.min_performance),
                      key=lambda n: n['node_id'])
    if len(eligible) < a.gateways:
        raise SystemExit(f'only {len(eligible)} eligible entry gateways')
    chosen = random.Random(a.seed).sample(eligible, a.gateways)
    gws = ',\n    '.join(f'"{n["ed25519_identity_pubkey"]}"' for n in chosen)
    cfg = f'''# mainnet link-observer run (generated by pick_gateways.py, seed {a.seed})
# gateways: {", ".join(f"{n['node_id']} {n['entry'].get('hostname') or n['ip_addresses'][0]} perf {n['performance']}" for n in chosen)}
network = "mainnet"
gateways = [
    {gws}
]
output_dir = "{a.output_dir}"
duration_s = {a.duration}
warmup_s = 5
drain_s = {a.drain}
message_size = 50000
messages_per_client_per_min = 6.0
pairing = "random-pairs"
seed = {a.seed}
[client]
loop_cover_traffic = true
poisson_sending = true
ack_wait_addition_s = 10
'''
    if a.groups:
        keys = ['average_packet_delay_ms', 'message_sending_average_delay_ms', 'loop_cover_traffic_average_delay_ms',
                'messages_per_client_per_min', 'message_size']
        total = 0
        for spec in a.groups.split(';'):
            f = spec.split(':'); name, count = f[0], int(f[1]); total += count
            cfg += f'[[group]]\nname = "{name}"\ncount = {count}\nstrategy = "{a.strategy}"\nsession = "{a.session}"\n'
            for k, v in zip(keys, f[2:]):
                if v != '':
                    cfg += f'{k} = {float(v) if k == "messages_per_client_per_min" else int(v)}\n'
        if total != a.clients:
            raise SystemExit(f'group counts add up to {total}, not --clients {a.clients}')
    else:
        cfg += f'[[group]]\nname = "mainnet"\ncount = {a.clients}\nstrategy = "{a.strategy}"\nsession = "{a.session}"\n'
    open(a.out, 'w').write(cfg)
    print(f'{a.out}: {a.clients} clients over gateways ' + ', '.join(str(n['node_id']) for n in chosen))


if __name__ == '__main__':
    main()
