#!/usr/bin/env python3
"""Generates a docker-compose file for the netem localnet: every node in its own network
namespace with its own IP on a bridge subnet, so that per-pair network delays can be emulated
with `tc netem` (see apply_netem.py).

It is a separate compose project (own container names, volume and data dir), so the ordinary
shared-namespace localnet in ../docker-compose.yml keeps working untouched.

Node i (1..L*M mixnodes, then gateways) gets IP SUBNET.(10+i) and keeps the usual port scheme
(mixnet 10000+i, verloc 20000+i, http 30000+i). Gateways publish their client websocket to
127.0.0.1:(WS_BASE+g) so clients on the host (self-test, load generator) can still connect;
the topology announces that address for clients and the bridge IP for node-to-node traffic.

Usage:
  gen_compose.py --mixes-per-layer 3 --gateways 2 --out docker-compose.netem.yml
"""
import argparse
from pathlib import Path

LAYERS = 3


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--mixes-per-layer", type=int, default=3)
    p.add_argument("--gateways", type=int, default=2)
    p.add_argument("--subnet", default="172.30.0", help="first three octets of the bridge subnet")
    p.add_argument("--ws-base", type=int, default=9100, help="host port of gateway g's client websocket = base+g")
    p.add_argument("--http-base", type=int, default=31000, help="host port of node i's http API = base+i")
    p.add_argument("--project", default="nym-netem", help="compose project / container name prefix")
    p.add_argument("--data-dir", default="data-netem", help="data dir (relative to nym-localnet/)")
    p.add_argument("--out", default="docker-compose.netem.yml")
    a = p.parse_args()

    mixes = LAYERS * a.mixes_per_layer
    first_gw = mixes + 1
    names = [(f"mix{i}", i, "mix") for i in range(1, mixes + 1)]
    names += [("gateway" if g == 0 else f"gateway{g + 1}", first_gw + g, "gateway") for g in range(a.gateways)]
    ip = lambda i: f"{a.subnet}.{10 + i}"

    env_topology = {
        "LOCALNET_SUBNET": f"{a.subnet}.",
        "LOCALNET_CLIENT_HOST": "127.0.0.1",
        "LOCALNET_WS_PORT_BASE": str(a.ws_base),
        "LOCALNET_MIXES_PER_LAYER": str(a.mixes_per_layer),
        "LOCALNET_GATEWAYS": str(a.gateways),
    }
    L = []
    L.append(f"# Generated by netem/gen_compose.py: {LAYERS}x{a.mixes_per_layer} mixnodes + {a.gateways} gateways,")
    L.append(f"# each in its own network namespace on {a.subnet}.0/24 (node i at {a.subnet}.(10+i)).")
    L.append(f"# Run with:  docker compose -p {a.project} -f {a.out} up -d")
    L.append("x-node: &node")
    L.append("  image: nym-localnet:latest")
    L.append("  volumes:")
    L.append(f"    - ./{a.data_dir}:/localnet")
    L.append(f"    - {a.project}-home:/root/.nym")
    L.append("    - ./docker/node.sh:/usr/local/bin/nym-localnet-node.sh:ro")
    L.append("    - ./docker/build_topology.py:/usr/local/bin/localnet_topology.py:ro")
    L.append("  cap_add: [NET_ADMIN]")
    L.append("  restart: unless-stopped")
    L.append("")
    L.append("services:")
    for name, i, kind in names:
        L.append(f"  {name}:")
        L.append("    <<: *node")
        L.append(f"    container_name: {a.project}-{name}")
        L.append(f"    networks: {{ nymnet: {{ ipv4_address: {ip(i)} }} }}")
        env = f"PUBLIC_IP: {ip(i)}, FIRST_GATEWAY: \"{first_gw}\", NETEM_TUNING: \"1\""
        # gateways write the wire-level packet log (for flow matching) into the shared /localnet
        # volume, one file per gateway process; mixnodes have no client handler so never write.
        if kind == "gateway":
            env += ", MIXCORR_WIRE_DIR: /localnet/wire"
        L.append(f"    environment: {{ {env} }}")
        # keep the TCP congestion window across idle gaps: node pairs see sparse traffic over
        # high-RTT emulated links, and restarting in slow start stalls the node's egress flushes
        L.append('    sysctls: { net.ipv4.tcp_slow_start_after_idle: "0" }')
        ports = [f'"127.0.0.1:{a.http_base + i}:{30000 + i}"']
        if kind == "gateway":
            g = i - first_gw
            ports.insert(0, f'"127.0.0.1:{a.ws_base + g}:{9000 + g}"')
            L.append('    devices: ["/dev/net/tun:/dev/net/tun"]')
        L.append(f"    ports: [{', '.join(ports)}]")
        L.append(f'    command: ["nym-localnet-node.sh", "{kind}", "{name}", "{i}"]')
        L.append("")
    L.append("  topology:")
    L.append("    <<: *node")
    L.append(f"    container_name: {a.project}-topology")
    L.append("    networks: [nymnet]")
    L.append("    environment:")
    for k, v in env_topology.items():
        L.append(f'      {k}: "{v}"')
    L.append(f"    depends_on: [{', '.join(n for n, _, _ in names)}]")
    L.append("    command:")
    L.append("      - sh")
    L.append("      - -c")
    L.append("      - |")
    L.append(f"        for f in {' '.join(n for n, _, _ in names)}; do")
    L.append('          while [ ! -f /localnet/$$f.json ]; do echo "waiting for $$f.json"; sleep 1; done')
    L.append("        done")
    L.append("        exec python3 -u /usr/local/bin/localnet_topology.py /localnet --watch")
    L.append("")
    L.append("networks:")
    L.append("  nymnet:")
    L.append("    driver: bridge")
    L.append(f"    ipam: {{ config: [{{ subnet: {a.subnet}.0/24 }}] }}")
    L.append("")
    L.append("volumes:")
    L.append(f"  {a.project}-home:")
    Path(a.out).write_text("\n".join(L) + "\n")
    print(f"wrote {a.out}: {mixes} mixnodes + {a.gateways} gateways on {a.subnet}.0/24; "
          f"gateway ws at 127.0.0.1:{a.ws_base}..{a.ws_base + a.gateways - 1}, data dir {a.data_dir}")
    if mixes + a.gateways > 30:
        print("NOTE: run netem/vm_sysctl.sh once per Docker start before applying delays: this many "
              "per-namespace nodes overflow the kernel's neighbour (ARP) table (see README).")


if __name__ == "__main__":
    main()
